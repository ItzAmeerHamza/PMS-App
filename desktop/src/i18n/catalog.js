export function localizeError(message, t) {
  if (!message) return "";
  if (EXACT_ERRORS[message]) return t(EXACT_ERRORS[message]);
  const inactive = message.match(/^(.*) is inactive$/);
  if (inactive) return t("error.inactive", { name: inactive[1] });
  const stock = message.match(/^Insufficient stock for (.*)$/);
  if (stock) return t("error.stock", { name: stock[1] });
  const failed = message.match(/^Request failed \((\d+)\)$/);
  if (failed) return t("error.request", { code: failed[1] });
  return message;
}
